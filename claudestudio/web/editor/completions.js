// Autocomplete for the script editor, from what the engine really has: the Luau VM's own library
// tables (asked once, `libraries`), the studio's class table (properties, methods, events,
// services, creatable classes, enums) and the open place itself (an instance's real children).
// Pure: complete(text, pos, ctx) -> { from, options: [{ label, type, detail, info }] } or null.
// ctx: { libs: { name: [keys] }, dm, script } (dm: the editor's DataModel; script: the open script).
// Prose (info, and the hover) is a one-line summary per member from Roblox's creator-docs, and a
// method's or event's parameter and return types are Roblox's (web/editor/apidocs.json, generated by
// tools/gen-apidocs.mjs); Claude Studio's own members have their docs in datamodel.js (STUDIO_OWN).
import { membersOf, serviceClasses, creatableClasses, classInfo, ENUMS, STUDIO_OWN } from '../datamodel.js';
import API from './apidocs.json' with { type: 'json' };

/** The one-line summary for a key ("BasePart.Anchored", "BasePart:PivotTo", "math.clamp", "Enum.Material"), or ''. */
export const docOf = key => STUDIO_OWN.get(key) || API.docs[key] || '';
const keyOf = (cls, name, kind) => cls + (kind === 'method' ? ':' : '.') + name;
/** A method's typed signature, Roblox's: "(targetCFrame: CFrame): ()"; with only the engine's parameter names, untyped. */
export function methodSignature(owner, name, params = []) {
  const s = API.sigs[owner + ':' + name];
  if (!s) return `(${params.join(', ')})`;
  return `(${s[0].map(([n, t, opt]) => `${n}: ${t}${opt ? '?' : ''}`).join(', ')}): ${s[1]}`;
}
/** An event's signal type, with what it passes: "RBXScriptSignal<(otherPart: BasePart)>". */
export function eventType(owner, name) {
  const s = API.sigs[owner + '.' + name];
  return s ? `RBXScriptSignal<(${s[0].map(([n, t]) => `${n}: ${t}`).join(', ')})>` : 'RBXScriptSignal';
}
const LUAU_NAMES = { bool: 'boolean' }; // the engine's property types, as Luau writes them
const propType = t => LUAU_NAMES[t] || t;

const KEYWORDS = ['and', 'break', 'continue', 'do', 'else', 'elseif', 'end', 'false', 'for', 'function', 'if', 'in', 'local', 'nil', 'not', 'or', 'repeat', 'return', 'then', 'true', 'until', 'while'];
const GLOBALS = ['game', 'workspace', 'script', 'print', 'warn', 'error', 'assert', 'pairs', 'ipairs', 'next', 'select', 'type', 'typeof', 'tostring', 'tonumber', 'pcall', 'xpcall', 'require', 'setmetatable', 'getmetatable', 'rawget', 'rawset', 'rawequal', 'unpack', 'wait', 'delay', 'spawn', 'tick', 'time', 'Enum'];

/** The VM's library tables (name -> sorted keys), asked from Luau itself: what scripts really get. */
export const LIBRARY_PROBE = `for _, name in {"math","string","table","task","coroutine","bit32","utf8","os","buffer","debug","Vector3","Vector2","CFrame","Color3","UDim","UDim2","Instance","TweenInfo","NumberRange","NumberSequence","NumberSequenceKeypoint","ColorSequence","ColorSequenceKeypoint"} do
  local v = getfenv()[name]; local keys = {}
  if type(v) == "table" then for k in pairs(v) do table.insert(keys, tostring(k)) end end
  table.sort(keys); print("@lib " .. name .. " " .. table.concat(keys, " "))
end`;
export function parseLibraries(lines) {
  const libs = {};
  for (const l of lines) { const m = /^@lib (\w+) ?(.*)$/.exec(l); if (m) libs[m[1]] = m[2] ? m[2].split(' ') : []; }
  return libs;
}

// What an expression is, as far as the text says: a library, Enum (or an Enum type), a class, an
// instance of the open place, or unknown. Expressions are dotted paths (a.b.c, game:GetService("X").Y).
function resolve(expr, text, ctx) {
  const parts = [], re = /(\w+)|:GetService\(\s*["'](\w+)["']\s*\)|:WaitForChild\(\s*["']([^"']+)["'][^)]*\)|:FindFirstChild\(\s*["']([^"']+)["'][^)]*\)|(\.)/g;
  let m, rest = expr;
  // Split into segments: names, and calls that give an instance.
  while ((m = re.exec(rest))) { if (m[1]) parts.push({ name: m[1] }); else if (m[2]) parts.push({ service: m[2] }); else if (m[3] || m[4]) parts.push({ child: m[3] || m[4] }); }
  if (!parts.length) return null;
  const head = parts[0].name;
  let cur;
  if (head === 'Enum') {
    if (parts.length === 1) return { enum: true };
    if (parts.length === 2 && ENUMS[parts[1].name]) return { enumType: parts[1].name };
    return null;
  }
  if (ctx.libs && ctx.libs[head] && parts.length === 1) return { lib: head };
  if (head === 'game') cur = { cls: 'DataModel', inst: null }; // its children are the services (below)
  else if (head === 'workspace') cur = { cls: 'Workspace', inst: ctx.dm ? ctx.dm.workspace : null };
  else if (head === 'script') cur = { cls: ctx.script ? ctx.script.ClassName : 'Script', inst: ctx.script || null };
  else { // a local: `local x = Instance.new("C")`, `= game:GetService("S")`, or `= <a resolvable path>`
    const decl = new RegExp(`local\\s+${head}\\s*=\\s*([^\\n]+)`).exec(text);
    if (!decl) return null;
    const rhs = decl[1].trim(), inew = /^Instance\.new\(\s*["'](\w+)["']/.exec(rhs);
    if (inew) cur = { cls: inew[1], inst: null };
    else if (rhs.split(/[.:]/)[0] !== head) cur = resolve(rhs.replace(/\s+$/, ''), text, ctx);
    if (!cur || !cur.cls) return null;
  }
  for (const p of parts.slice(1)) {
    if (p.service) { const s = ctx.dm && ctx.dm.services && ctx.dm.services[p.service]; cur = { cls: p.service, inst: s || null }; continue; }
    const name = p.name || p.child;
    if (cur.cls === 'DataModel' && ctx.dm && ctx.dm.services[name]) { cur = { cls: name, inst: ctx.dm.services[name] }; continue; }
    const kid = cur.inst && cur.inst.children.find(c => c.props.Name === name);
    if (kid) { cur = { cls: kid.ClassName, inst: kid }; continue; }
    if (p.name === 'Parent' && cur.inst && cur.inst.parent) { cur = { cls: cur.inst.parent.ClassName, inst: cur.inst.parent }; continue; }
    const prop = p.name && membersOf(cur.cls).props.find(x => x.name === p.name);
    if (prop && prop.type === 'Instance') { cur = { cls: 'Instance', inst: null }; continue; }
    if (cur.cls === 'DataModel' && p.name && classInfo(p.name) && classInfo(p.name).service) { cur = { cls: p.name, inst: ctx.dm && ctx.dm.services[p.name] }; continue; }
    return null;
  }
  return cur;
}

const opt = (label, type, detail, info) => info ? { label, type, detail, info } : { label, type, detail };
export function complete(text, pos, ctx = {}) {
  const before = text.slice(0, pos);
  // Inside a string argument: GetService, Instance.new, WaitForChild / FindFirstChild.
  let m = /(?:game|\w+):GetService\(\s*["'](\w*)$/.exec(before);
  if (m) return { from: pos - m[1].length, options: serviceClasses().map(c => opt(c, 'class', 'service', docOf(c))) };
  m = /Instance\.new\(\s*["'](\w*)$/.exec(before);
  if (m) return { from: pos - m[1].length, options: creatableClasses().map(c => opt(c, 'class', 'class', docOf(c))) };
  m = /([\w.:"'()\s]*?):(?:WaitForChild|FindFirstChild)\(\s*["']([^"']*)$/.exec(before);
  if (m) { const r = resolve(m[1].trim(), text, ctx); if (r && r.inst) return { from: pos - m[2].length, options: r.inst.children.map(c => opt(c.props.Name, 'variable', c.ClassName)) }; return null; }
  if (/["'`][^"'`\n]*$/.test(before.split('\n').pop().replace(/(["'`])(?:\\.|(?!\1).)*\1/g, ''))) return null; // in some other string
  if (/--[^\n]*$/.test(before.split('\n').pop())) return null; // in a comment
  // After a dot or a colon: members of what's before it.
  m = /((?:\w+|:GetService\([^)]*\)|:(?:WaitForChild|FindFirstChild)\([^)]*\))(?:\s*[.:]\s*(?:\w+|GetService\([^)]*\)|(?:WaitForChild|FindFirstChild)\([^)]*\)))*)\s*([.:])(\w*)$/.exec(before);
  if (m) {
    const r = resolve(m[1], text, ctx), from = pos - m[3].length, colon = m[2] === ':';
    if (!r) return null;
    if (r.lib) return colon ? null : { from, options: ctx.libs[r.lib].map(k => opt(k, /^[A-Z]/.test(k) || ['pi', 'huge', 'e', 'nan', 'tau', 'phi', 'sqrt2', 'zero', 'one', 'identity'].includes(k) ? 'constant' : 'function', r.lib, docOf(r.lib + '.' + k))) };
    if (r.enum) return colon ? null : { from, options: Object.keys(ENUMS).sort().map(e => opt(e, 'enum', 'Enum', docOf('Enum.' + e))) };
    if (r.enumType) return colon ? null : { from, options: Object.keys(ENUMS[r.enumType]).map(e => opt(e, 'enum', 'Enum.' + r.enumType, docOf(`Enum.${r.enumType}.${e}`))) };
    const mem = membersOf(r.cls);
    if (colon) return { from, options: mem.methods.map(x => opt(x.name, 'method', methodSignature(x.owner, x.name, x.params), docOf(keyOf(x.owner, x.name, 'method')))) };
    const kids = r.inst ? r.inst.children.map(c => opt(c.props.Name, 'variable', c.ClassName)) : [];
    const services = r.cls === 'DataModel' ? serviceClasses().map(c => opt(c, 'class', 'service', docOf(c))) : [];
    const always = [opt('Parent', 'property', 'Instance', API.docs['Instance.Parent']), opt('ClassName', 'property', 'string', API.docs['Instance.ClassName'])]; // every instance has these (the engine keeps them outside its property lists)
    return { from, options: [...kids, ...services, ...mem.props.map(x => opt(x.name, 'property', propType(x.type), docOf(keyOf(x.owner, x.name)))), ...always, ...mem.events.map(x => opt(x.name, 'event', 'event', docOf(keyOf(x.owner, x.name))))] };
  }
  // A plain word: keywords, globals, libraries, and the script's own locals and functions.
  m = /(?:^|[^\w.:])(\w+)$/.exec(before);
  if (!m) return null;
  const locals = new Set();
  for (const d of text.matchAll(/\b(?:local\s+function|function|local)\s+([\w, ]+)/g)) d[1].split(',').forEach(n => { n = n.trim(); if (/^\w+$/.test(n)) locals.add(n); });
  for (const d of text.matchAll(/\bfor\s+([\w, ]+)\s+(?:=|in)\b/g)) d[1].split(',').forEach(n => { n = n.trim(); if (n) locals.add(n); });
  locals.delete(m[1]);
  const seen = new Set(), options = [];
  const add = (label, type, detail, info) => { if (!seen.has(label)) { seen.add(label); options.push(opt(label, type, detail, info)); } };
  [...locals].forEach(n => add(n, 'variable', 'local'));
  GLOBALS.forEach(g => add(g, 'variable', 'global', docOf(g)));
  Object.keys(ctx.libs || {}).forEach(l => add(l, 'namespace', 'library', docOf(l)));
  KEYWORDS.forEach(k => add(k, 'keyword', 'keyword'));
  return { from: pos - m[1].length, options };
}

// Hover: what the word at `pos` is, from the same sources as completion. Returns
// { from, to, title, doc, lines } or null. title: "Part.Anchored: boolean", "Part:PivotTo(targetCFrame: CFrame): ()";
// doc: its one-line summary ('' if none); lines: facts (owner class, read-only, Claude Studio's own, the instance's path).
const OWN = "Claude Studio's own (not in Roblox)";
export function describe(text, pos, ctx = {}) {
  let a = pos, b = pos;
  while (a > 0 && /\w/.test(text[a - 1])) a--;
  while (b < text.length && /\w/.test(text[b])) b++;
  if (a === b) return null;
  const word = text.slice(a, b), lineStart = text.lastIndexOf('\n', a - 1) + 1, before = text.slice(lineStart, a);
  if (/--/.test(before) || /["'`][^"'`]*$/.test(before.replace(/(["'`])(?:\\.|(?!\1).)*\1/g, ''))) return null; // a comment or a string
  const out = (title, doc, ...lines) => ({ from: a, to: b, title, doc: doc || '', lines: lines.filter(Boolean) });
  const sep = /([.:])\s*$/.exec(before);
  if (sep) {
    const exprM = /((?:\w+|:GetService\([^)]*\)|:(?:WaitForChild|FindFirstChild)\([^)]*\))(?:\s*[.:]\s*(?:\w+|GetService\([^)]*\)|(?:WaitForChild|FindFirstChild)\([^)]*\)))*)\s*[.:]\s*$/.exec(before);
    const r = exprM && resolve(exprM[1], text, ctx);
    if (!r) return null;
    if (r.lib) return ctx.libs[r.lib].includes(word) ? out(`${r.lib}.${word}`, docOf(`${r.lib}.${word}`), `in Luau's ${r.lib} library`) : null;
    if (r.enum) return ENUMS[word] ? out(`Enum.${word}`, docOf('Enum.' + word), `${Object.keys(ENUMS[word]).length} items`, STUDIO_OWN.has('Enum.' + word) && OWN) : null;
    if (r.enumType) return word in ENUMS[r.enumType] ? out(`Enum.${r.enumType}.${word}`, docOf(`Enum.${r.enumType}.${word}`), 'enum item') : null;
    const mem = membersOf(r.cls), kid = r.inst && r.inst.children.find(c => c.props.Name === word);
    if (kid) return out(`${word}: ${kid.ClassName}`, docOf(kid.ClassName), `${fullName(kid)} in this place`);
    const m = mem.methods.find(x => x.name === word), p = mem.props.find(x => x.name === word), e = mem.events.find(x => x.name === word);
    if (m) return out(`${r.cls}:${word}${methodSignature(m.owner, word, m.params)}`, docOf(keyOf(m.owner, word, 'method')), `method of ${m.owner}`);
    if (p) return out(`${r.cls}.${word}: ${propType(p.type)}`, docOf(keyOf(p.owner, word)), `property of ${p.owner}`, p.readOnly && 'read-only to scripts', p.own && OWN);
    if (e) return out(`${r.cls}.${word}: ${eventType(e.owner, word)}`, docOf(keyOf(e.owner, word)), `event of ${e.owner}`);
    if (word === 'Parent') return out(`${r.cls}.Parent: Instance`, docOf('Instance.Parent'), 'property of Instance');
    if (word === 'ClassName') return out(`${r.cls}.ClassName: string`, docOf('Instance.ClassName'), 'property of Instance', 'read-only to scripts');
    return null;
  }
  if (word === 'game') return out('game: DataModel', docOf('game'), 'the place; its children are the services');
  if (word === 'workspace') return out('workspace: Workspace', docOf('workspace'), 'the 3D world (game.Workspace)');
  if (word === 'script') return out(`script: ${ctx.script ? ctx.script.ClassName : 'Script'}`, docOf('script'), ctx.script && `${fullName(ctx.script)}, the script this code runs as`);
  if (word === 'Enum') return out('Enum', docOf('Enum'), `${Object.keys(ENUMS).length} enum types`);
  if (ctx.libs && ctx.libs[word]) return out(word, docOf(word), `Luau library: ${ctx.libs[word].length} members`);
  if (KEYWORDS.includes(word)) return out(word, '', 'keyword');
  const decl = new RegExp(`local\\s+${word}\\s*=\\s*([^\\n]+)`).exec(text);
  if (decl) { const r = resolve(word, text, ctx); return out(`local ${word}${r && r.cls ? ': ' + r.cls : ''}`, '', `= ${decl[1].trim().slice(0, 60)}`); }
  if (GLOBALS.includes(word)) return out(word, docOf(word), 'global');
  return null;
}
const fullName = i => { const n = []; for (let x = i; x && x.parent; x = x.parent) n.unshift(x.props.Name); return n.join('.'); };
