// Roblox's BrickColor table, generated from creator-docs `datatypes/BrickColor.yaml` (CC-BY-4.0):
// each colour's Number, Name, RGB (0-255) and 128-colour palette index.
//
// One generated source, web/brickcolors.json, feeds both tables: the JS one (web/brickcolor.js
// imports it) and the VM's (luau/brickcolor_table.h, written from the JSON; luau/build.sh rewrites it
// before every build, so the two can't drift).
//   node tools/gen-brickcolors.mjs <creator-docs checkout>   docs -> web/brickcolors.json and the header
//   node tools/gen-brickcolors.mjs --header                  web/brickcolors.json -> the header
// (Fetching creator-docs: see tools/gen-apidocs.mjs.)
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const JSON_OUT = new URL('../web/brickcolors.json', import.meta.url);
const HEADER_OUT = new URL('../luau/brickcolor_table.h', import.meta.url);

function fromDocs(docsRoot) {
  const yaml = fs.readFileSync(path.join(docsRoot, 'content/en-us/reference/engine/datatypes/BrickColor.yaml'), 'utf8');
  const colors = [];
  for (const row of yaml.matchAll(/<tr>([\s\S]*?)<\/tr>/g)) {
    const cells = [...row[1].matchAll(/<td[^>]*>([\s\S]*?)<\/td>/g)].map(m => m[1].trim());
    if (cells.length !== 6) continue; // the header row has <th>s
    const code = s => { const m = /<code>([^<]*)<\/code>/.exec(s); return m ? m[1] : null; };
    const number = +code(cells[2]), palette = code(cells[3]) === null ? -1 : +code(cells[3]), rgb = code(cells[4]).split(',').map(Number);
    if (!Number.isInteger(number) || rgb.length !== 3 || rgb.some(v => !Number.isInteger(v) || v < 0 || v > 255)) throw new Error('bad row: ' + cells.join(' | '));
    colors.push([number, cells[1], ...rgb, palette]);
  }
  // Checks: unique numbers, and a palette of exactly 0..127, each once.
  if (new Set(colors.map(c => c[0])).size !== colors.length) throw new Error('duplicate numbers');
  // Some names repeat (Roblox's own table has them); BrickColor.new(name) gives the first, by table order.
  const names = colors.map(c => c[1]), dup = names.filter((n, i) => names.indexOf(n) !== i);
  if (dup.length) console.log('names that repeat: ' + [...new Set(dup)].map(n => n + ' (' + colors.filter(c => c[1] === n).map(c => c[0]).join(', ') + ')').join('; '));
  const pal = colors.map(c => c[5]).filter(p => p >= 0).sort((a, b) => a - b);
  if (pal.length !== 128 || pal.some((p, i) => p !== i)) throw new Error(`palette isn't 0..127 (${pal.length} entries)`);
  let rev = '?'; try { rev = execFileSync('git', ['-C', docsRoot, 'log', '-1', '--format=%h %cs'], { encoding: 'utf8' }).trim(); } catch { /* not a checkout */ }
  return { source: `Roblox/creator-docs ${rev}, datatypes/BrickColor.yaml, CC-BY-4.0. [number, name, r, g, b (0-255), palette index (-1: none)]`, colors };
}

function header(data) {
  const esc = s => JSON.stringify(s); // the names are plain ASCII
  if (data.colors.some(c => /[^\x20-\x7e]/.test(c[1]))) throw new Error('non-ASCII name');
  return `// Generated by tools/gen-brickcolors.mjs from web/brickcolors.json; don't edit.
// ${data.source}
struct BrickColorEntry { int number; const char* name; unsigned char r, g, b; int palette; };
static const BrickColorEntry BRICKCOLORS[] = {
${data.colors.map(([n, name, r, g, b, p]) => `    { ${n}, ${esc(name)}, ${r}, ${g}, ${b}, ${p} },`).join('\n')}
};
static const int BRICKCOLOR_COUNT = ${data.colors.length};
`;
}

const arg = process.argv[2];
if (!arg) { console.error('usage: node tools/gen-brickcolors.mjs <creator-docs checkout> | --header'); process.exit(1); }
let data;
if (arg === '--header') data = JSON.parse(fs.readFileSync(JSON_OUT, 'utf8'));
else { data = fromDocs(arg); fs.writeFileSync(JSON_OUT, JSON.stringify(data) + '\n'); console.log(`web/brickcolors.json: ${data.colors.length} colours`); }
fs.writeFileSync(HEADER_OUT, header(data));
console.log(`luau/brickcolor_table.h: ${data.colors.length} colours`);
